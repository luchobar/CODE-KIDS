-- =============================================================================
-- CODEKIDS — TAREA 1: Modelo Lógico y Relacional Normalizado en 3FN
-- Archivo: /sql/01_schema_13_tables.sql
-- Motor: PostgreSQL 16+ / Supabase
-- Descripción: Script DDL completo en Tercera Forma Normal (3FN) con llaves
--              primarias (PK), llaves foráneas (FK), restricciones de dominio
--              (CHECK, UNIQUE, NOT NULL) e integridad referencial explícita.
-- =============================================================================

BEGIN;

-- Limpieza preventiva en orden inverso de dependencias referenciales
DROP TABLE IF EXISTS entregas_retos CASCADE;
DROP TABLE IF EXISTS retos_aula CASCADE;
DROP TABLE IF EXISTS matriculas_aula CASCADE;
DROP TABLE IF EXISTS aulas CASCADE;
DROP TABLE IF EXISTS progreso_misiones_usuario CASCADE;
DROP TABLE IF EXISTS misiones CASCADE;
DROP TABLE IF EXISTS mundos CASCADE;
DROP TABLE IF EXISTS insignias_usuario CASCADE;
DROP TABLE IF EXISTS catalogo_insignias CASCADE;
DROP TABLE IF EXISTS inventario_avatares_usuario CASCADE;
DROP TABLE IF EXISTS perfiles_gamificacion CASCADE;
DROP TABLE IF EXISTS catalogo_avatares CASCADE;
DROP TABLE IF EXISTS usuarios CASCADE;
DROP TABLE IF EXISTS roles CASCADE;

-- Extensiones requeridas
CREATE EXTENSION IF NOT EXISTS citext;
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- -----------------------------------------------------------------------------
-- TABLA 1: roles
-- Normalización 3FN: Catálogo de roles del sistema sin dependencia transitiva
-- -----------------------------------------------------------------------------
CREATE TABLE roles (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol VARCHAR(20) NOT NULL UNIQUE
        CHECK (nombre_rol IN ('estudiante', 'docente', 'admin')),
    descripcion VARCHAR(200) NOT NULL
);

-- -----------------------------------------------------------------------------
-- TABLA 2: usuarios
-- Almacena las credenciales y metadatos de identidad vinculados a roles (3FN)
-- -----------------------------------------------------------------------------
CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_uid UUID NULL UNIQUE,
    correo CITEXT NOT NULL UNIQUE,
    nombre VARCHAR(120) NOT NULL DEFAULT 'Explorador',
    rol VARCHAR(20) NOT NULL DEFAULT 'estudiante'
        REFERENCES roles(nombre_rol) ON UPDATE CASCADE ON DELETE RESTRICT,
    rol_id SMALLINT NOT NULL DEFAULT 1
        REFERENCES roles(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    contrasena_hash TEXT NULL,
    correo_verificado_en TIMESTAMPTZ NULL,
    es_perfil_rapido BOOLEAN NOT NULL DEFAULT FALSE,
    etiqueta_rapida VARCHAR(60) NULL,
    intentos_fallidos SMALLINT NOT NULL DEFAULT 0 CHECK (intentos_fallidos >= 0),
    bloqueado_hasta TIMESTAMPTZ NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    ultimo_acceso_en TIMESTAMPTZ NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_usuarios_rol ON usuarios(rol);
CREATE INDEX idx_usuarios_activo ON usuarios(activo);

-- -----------------------------------------------------------------------------
-- TABLA 3: catalogo_avatares
-- Catálogo maestro de compañeros desbloqueables en la tienda gamificada
-- -----------------------------------------------------------------------------
CREATE TABLE catalogo_avatares (
    id VARCHAR(32) PRIMARY KEY,
    nombre_visible VARCHAR(80) NOT NULL,
    costo_monedas INTEGER NOT NULL DEFAULT 0 CHECK (costo_monedas >= 0),
    tono_tema VARCHAR(20) NOT NULL DEFAULT 'blue'
        CHECK (tono_tema IN ('peach', 'lav', 'mint', 'yellow', 'blue')),
    descripcion VARCHAR(240) NOT NULL,
    es_inicial BOOLEAN NOT NULL DEFAULT FALSE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- -----------------------------------------------------------------------------
-- TABLA 4: perfiles_gamificacion
-- Relación 1:1 con usuarios (HUD: XP, saldo de monedas, racha y avatar activo)
-- -----------------------------------------------------------------------------
CREATE TABLE perfiles_gamificacion (
    usuario_id BIGINT PRIMARY KEY
        REFERENCES usuarios(id) ON DELETE CASCADE,
    puntos_xp INTEGER NOT NULL DEFAULT 0 CHECK (puntos_xp >= 0),
    nivel_actual INTEGER GENERATED ALWAYS AS ((puntos_xp / 100) + 1) STORED,
    saldo_monedas INTEGER NOT NULL DEFAULT 0 CHECK (saldo_monedas >= 0),
    dias_racha INTEGER NOT NULL DEFAULT 1 CHECK (dias_racha >= 0),
    ultima_fecha_actividad DATE NOT NULL DEFAULT CURRENT_DATE,
    avatar_activo_id VARCHAR(32) NOT NULL DEFAULT 'dragon'
        REFERENCES catalogo_avatares(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    sonido_habilitado BOOLEAN NOT NULL DEFAULT TRUE,
    puntajes_diagnostico JSONB NOT NULL DEFAULT '{"Secuencias": 75, "Bucles": 45, "Condicionales": 80, "Descomposición": 55}'::jsonb,
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- -----------------------------------------------------------------------------
-- TABLA 5: inventario_avatares_usuario
-- Entidad asociativa N:M entre usuarios y catalogo_avatares (3FN)
-- -----------------------------------------------------------------------------
CREATE TABLE inventario_avatares_usuario (
    usuario_id BIGINT NOT NULL
        REFERENCES usuarios(id) ON DELETE CASCADE,
    avatar_id VARCHAR(32) NOT NULL
        REFERENCES catalogo_avatares(id) ON DELETE CASCADE,
    desbloqueado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (usuario_id, avatar_id)
);

CREATE INDEX idx_inventario_avatar ON inventario_avatares_usuario(avatar_id);

-- -----------------------------------------------------------------------------
-- TABLA 6: catalogo_insignias
-- Catálogo maestro de medallas por logros de pensamiento computacional
-- -----------------------------------------------------------------------------
CREATE TABLE catalogo_insignias (
    id VARCHAR(40) PRIMARY KEY,
    codigo_insignia VARCHAR(40) NOT NULL UNIQUE,
    nombre VARCHAR(80) NOT NULL,
    titulo VARCHAR(80) NOT NULL,
    descripcion VARCHAR(200) NOT NULL,
    tematica_habilidad VARCHAR(40) NOT NULL DEFAULT 'Secuencias',
    icono_url VARCHAR(255) NOT NULL DEFAULT '/images/badge-default.svg',
    nombre_icono VARCHAR(40) NOT NULL DEFAULT 'Trophy',
    requisito_xp INTEGER NOT NULL DEFAULT 50 CHECK (requisito_xp >= 0)
);

-- -----------------------------------------------------------------------------
-- TABLA 7: insignias_usuario
-- Entidad asociativa N:M entre usuarios y catalogo_insignias (3FN)
-- -----------------------------------------------------------------------------
CREATE TABLE insignias_usuario (
    usuario_id BIGINT NOT NULL
        REFERENCES usuarios(id) ON DELETE CASCADE,
    insignia_id VARCHAR(40) NOT NULL
        REFERENCES catalogo_insignias(id) ON DELETE CASCADE,
    fecha_desbloqueo TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    otorgada_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (usuario_id, insignia_id)
);

-- -----------------------------------------------------------------------------
-- TABLA 8: mundos
-- Mundos temáticos del mapa de misiones (Secuencias, Bucles, Condicionales...)
-- -----------------------------------------------------------------------------
CREATE TABLE mundos (
    id VARCHAR(40) PRIMARY KEY,
    slug VARCHAR(60) UNIQUE,
    orden_mundo SMALLINT NOT NULL UNIQUE CHECK (orden_mundo > 0),
    tematica_habilidad VARCHAR(40) NOT NULL
        CHECK (tematica_habilidad IN ('Secuencias', 'Bucles', 'Condicionales', 'Funciones', 'Python', 'HTML5', 'JavaScript')),
    titulo VARCHAR(120) NOT NULL,
    subtitulo VARCHAR(240) NOT NULL DEFAULT '',
    descripcion TEXT NULL,
    tecnologia VARCHAR(40) NULL,
    icono VARCHAR(40) NULL,
    tono_color VARCHAR(24) NOT NULL DEFAULT 'forest',
    url_imagen_banner VARCHAR(255) NOT NULL DEFAULT '/images/world-forest.png',
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

-- -----------------------------------------------------------------------------
-- TABLA 9: misiones
-- Ejercicios interactivos asociados a un mundo (Relación 1:N desde mundos)
-- -----------------------------------------------------------------------------
CREATE TABLE misiones (
    id VARCHAR(50) PRIMARY KEY,
    slug VARCHAR(80) UNIQUE,
    mundo_id VARCHAR(40) NOT NULL
        REFERENCES mundos(id) ON DELETE CASCADE,
    orden_etapa SMALLINT NOT NULL CHECK (orden_etapa BETWEEN 1 AND 20),
    nivel_dificultad VARCHAR(30) NOT NULL DEFAULT 'Inicio'
        CHECK (nivel_dificultad IN ('Inicio', 'En camino', 'Explorador', 'Laboratorio')),
    plantilla_id VARCHAR(40) NOT NULL DEFAULT 'sequence-order'
        CHECK (plantilla_id IN ('sequence-order', 'loop-count', 'if-choice', 'python-script', 'python-code', 'html-markup', 'javascript-script')),
    nombre_corto VARCHAR(80) NOT NULL DEFAULT 'Misión',
    titulo_ejercicio VARCHAR(120) NOT NULL,
    descripcion VARCHAR(240) NOT NULL DEFAULT '',
    instrucciones TEXT NOT NULL DEFAULT '',
    bloque_requerido VARCHAR(40) NULL,
    configuracion_tablero JSONB NOT NULL DEFAULT '{}'::jsonb,
    programa_semilla JSONB NOT NULL DEFAULT '[]'::jsonb,
    recompensa_xp INTEGER NOT NULL DEFAULT 10 CHECK (recompensa_xp >= 0),
    recompensa_monedas INTEGER NOT NULL DEFAULT 10 CHECK (recompensa_monedas >= 0),
    CONSTRAINT uq_mundo_orden_etapa UNIQUE (mundo_id, orden_etapa)
);

CREATE INDEX idx_misiones_mundo_etapa ON misiones (mundo_id, orden_etapa);

-- -----------------------------------------------------------------------------
-- TABLA 10: progreso_misiones_usuario
-- Registro de avance, estrellas, intentos y evidencia de cada estudiante por misión
-- -----------------------------------------------------------------------------
CREATE TABLE progreso_misiones_usuario (
    usuario_id BIGINT NOT NULL
        REFERENCES usuarios(id) ON DELETE CASCADE,
    mision_id VARCHAR(50) NOT NULL
        REFERENCES misiones(id) ON DELETE CASCADE,
    estado VARCHAR(20) NOT NULL DEFAULT 'bloqueada'
        CHECK (estado IN ('bloqueada', 'disponible', 'completada')),
    estrellas_ganadas SMALLINT NOT NULL DEFAULT 0
        CHECK (estrellas_ganadas BETWEEN 0 AND 3),
    cantidad_intentos INTEGER NOT NULL DEFAULT 0
        CHECK (cantidad_intentos >= 0),
    ultima_evidencia TEXT NULL,
    estado_espacio_trabajo JSONB NULL,
    completada_en TIMESTAMPTZ NULL,
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (usuario_id, mision_id)
);

CREATE INDEX idx_progreso_usuario_estado ON progreso_misiones_usuario (usuario_id, estado);
CREATE INDEX idx_progreso_mision_intentos ON progreso_misiones_usuario (mision_id, cantidad_intentos DESC);

-- -----------------------------------------------------------------------------
-- TABLA 11: aulas
-- Cursos académicos gestionados por un docente (Relación 1:N desde usuarios)
-- -----------------------------------------------------------------------------
CREATE TABLE aulas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    docente_id BIGINT NOT NULL
        REFERENCES usuarios(id) ON DELETE RESTRICT,
    nombre_grupo VARCHAR(120) NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    grado VARCHAR(30) NOT NULL DEFAULT '5° Primaria',
    codigo_acceso VARCHAR(20) NOT NULL UNIQUE,
    codigo_grupo VARCHAR(20) NOT NULL UNIQUE,
    anio_escolar SMALLINT NOT NULL DEFAULT 2026,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_aulas_docente ON aulas(docente_id);

-- -----------------------------------------------------------------------------
-- TABLA 12: matriculas_aula
-- Inscripción N:M de estudiantes en aulas académicas (3FN)
-- -----------------------------------------------------------------------------
CREATE TABLE matriculas_aula (
    aula_id BIGINT NOT NULL
        REFERENCES aulas(id) ON DELETE CASCADE,
    estudiante_id BIGINT NOT NULL
        REFERENCES usuarios(id) ON DELETE CASCADE,
    fecha_matricula TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    matriculado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (aula_id, estudiante_id)
);

CREATE INDEX idx_matriculas_estudiante ON matriculas_aula(estudiante_id);

-- -----------------------------------------------------------------------------
-- TABLA 13: retos_aula
-- Actividades asignadas por un docente a un aula vinculadas a una misión
-- -----------------------------------------------------------------------------
CREATE TABLE retos_aula (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aula_id BIGINT NOT NULL
        REFERENCES aulas(id) ON DELETE CASCADE,
    mision_id VARCHAR(50) NOT NULL
        REFERENCES misiones(id) ON DELETE RESTRICT,
    titulo VARCHAR(140) NOT NULL,
    instrucciones TEXT NOT NULL DEFAULT '',
    tematica_habilidad VARCHAR(40) NOT NULL DEFAULT 'Secuencias',
    fecha_limite TIMESTAMPTZ NULL DEFAULT (NOW() + INTERVAL '14 days'),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_retos_aula_id ON retos_aula(aula_id);

-- -----------------------------------------------------------------------------
-- TABLA 14: entregas_retos
-- Entregas y calificaciones de los estudiantes para cada reto de aula
-- Soporta escala 0.00-5.00 (puntuacion) para informes académicos y 0-100 (puntaje)
-- -----------------------------------------------------------------------------
CREATE TABLE entregas_retos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reto_id BIGINT NOT NULL
        REFERENCES retos_aula(id) ON DELETE CASCADE,
    estudiante_id BIGINT NOT NULL
        REFERENCES usuarios(id) ON DELETE CASCADE,
    puntuacion NUMERIC(3,2) NOT NULL DEFAULT 0.00
        CHECK (puntuacion BETWEEN 0.00 AND 5.00),
    puntaje SMALLINT NOT NULL DEFAULT 0
        CHECK (puntaje BETWEEN 0 AND 100),
    cantidad_intentos INTEGER NOT NULL DEFAULT 1
        CHECK (cantidad_intentos > 0),
    logrado BOOLEAN NOT NULL DEFAULT FALSE,
    texto_evidencia TEXT NOT NULL DEFAULT 'Reto enviado',
    retroalimentacion_ia TEXT NOT NULL DEFAULT '',
    recomendacion_docente TEXT NOT NULL DEFAULT '',
    estado VARCHAR(20) NOT NULL DEFAULT 'calificado'
        CHECK (estado IN ('pendiente', 'entregado', 'calificado', 'revisado')),
    fuente_evaluacion VARCHAR(30) NOT NULL DEFAULT 'ollama',
    fecha_entrega TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    entregado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_reto_estudiante UNIQUE (reto_id, estudiante_id)
);

CREATE INDEX idx_entregas_estudiante ON entregas_retos(estudiante_id);
CREATE INDEX idx_entregas_puntuacion ON entregas_retos(puntuacion);

-- -----------------------------------------------------------------------------
-- TRIGGERS DE INTEGRIDAD Y SINCRONIZACIÓN DE COLUMNAS EN 3FN
-- -----------------------------------------------------------------------------

-- 1. Sincroniza rol <-> rol_id en usuarios
CREATE OR REPLACE FUNCTION fn_sync_usuario_rol()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.rol IS NOT NULL THEN
        SELECT id INTO NEW.rol_id FROM roles WHERE nombre_rol = NEW.rol;
    ELSIF NEW.rol_id IS NOT NULL THEN
        SELECT nombre_rol INTO NEW.rol FROM roles WHERE id = NEW.rol_id;
    END IF;
    IF NEW.rol_id IS NULL THEN
        NEW.rol_id := 1;
        NEW.rol := 'estudiante';
    END IF;
    NEW.actualizado_en := NOW();
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_sync_usuario_rol
BEFORE INSERT OR UPDATE ON usuarios
FOR EACH ROW EXECUTE FUNCTION fn_sync_usuario_rol();

-- 2. Sincroniza aulas (nombre_grupo <-> nombre, codigo_acceso <-> codigo_grupo)
CREATE OR REPLACE FUNCTION fn_sync_aula_fields()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.nombre_grupo IS NULL AND NEW.nombre IS NOT NULL THEN
        NEW.nombre_grupo := NEW.nombre;
    ELSIF NEW.nombre IS NULL AND NEW.nombre_grupo IS NOT NULL THEN
        NEW.nombre := NEW.nombre_grupo;
    END IF;

    IF NEW.codigo_acceso IS NULL AND NEW.codigo_grupo IS NOT NULL THEN
        NEW.codigo_acceso := NEW.codigo_grupo;
    ELSIF NEW.codigo_grupo IS NULL AND NEW.codigo_acceso IS NOT NULL THEN
        NEW.codigo_grupo := NEW.codigo_acceso;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_sync_aula_fields
BEFORE INSERT OR UPDATE ON aulas
FOR EACH ROW EXECUTE FUNCTION fn_sync_aula_fields();

-- 3. Sincroniza entregas_retos: escala 0.0-5.0 (puntuacion) <-> escala 0-100 (puntaje)
CREATE OR REPLACE FUNCTION fn_sync_entrega_puntuacion()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF (NEW.puntuacion IS NULL OR NEW.puntuacion = 0) AND NEW.puntaje > 0 THEN
        NEW.puntuacion := ROUND((NEW.puntaje / 20.0)::numeric, 2);
    ELSIF (NEW.puntaje IS NULL OR NEW.puntaje = 0) AND NEW.puntuacion > 0 THEN
        NEW.puntaje := ROUND(NEW.puntuacion * 20)::smallint;
    END IF;
    IF NEW.fecha_entrega IS NULL THEN
        NEW.fecha_entrega := COALESCE(NEW.entregado_en, NOW());
    END IF;
    IF NEW.entregado_en IS NULL THEN
        NEW.entregado_en := COALESCE(NEW.fecha_entrega, NOW());
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_sync_entrega_puntuacion
BEFORE INSERT OR UPDATE ON entregas_retos
FOR EACH ROW EXECUTE FUNCTION fn_sync_entrega_puntuacion();

COMMIT;
