-- 1. Sincroniza rol <-> rol_id en usuarios
CREATE OR REPLACE FUNCTION fn_sync_usuario_rol()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.rol IS NOT NULL THEN
        SELECT id INTO NEW.rol_id FROM roles WHERE nombre_rol = NEW.rol;
    ELSIF NEW.rol_id IS NOT NULL THEN
        SELECT nombre_rol INTO NEW.rol FROM roles WHERE id = NEW.rol_id;
    END IF;
    IF NEW.rol_id IS NULL THEN
        NEW.rol_id := 1;
        NEW.rol := 'estudiante';
    END IF;
    NEW.actualizado_en := NOW();
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_sync_usuario_rol
BEFORE INSERT OR UPDATE ON usuarios
FOR EACH ROW EXECUTE FUNCTION fn_sync_usuario_rol();

-- 2. Sincroniza aulas (nombre_grupo <-> nombre, codigo_acceso <-> codigo_grupo)
CREATE OR REPLACE FUNCTION fn_sync_aula_fields()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.nombre_grupo IS NULL AND NEW.nombre IS NOT NULL THEN
        NEW.nombre_grupo := NEW.nombre;
    ELSIF NEW.nombre IS NULL AND NEW.nombre_grupo IS NOT NULL THEN
        NEW.nombre := NEW.nombre_grupo;
    END IF;

    IF NEW.codigo_acceso IS NULL AND NEW.codigo_grupo IS NOT NULL THEN
        NEW.codigo_acceso := NEW.codigo_grupo;
    ELSIF NEW.codigo_grupo IS NULL AND NEW.codigo_acceso IS NOT NULL THEN
        NEW.codigo_grupo := NEW.codigo_acceso;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_sync_aula_fields
BEFORE INSERT OR UPDATE ON aulas
FOR EACH ROW EXECUTE FUNCTION fn_sync_aula_fields();

-- 3. Sincroniza entregas_retos: escala 0.0-5.0 (puntuacion) <-> escala 0-100 (puntaje)
CREATE OR REPLACE FUNCTION fn_sync_entrega_puntuacion()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF (NEW.puntuacion IS NULL OR NEW.puntuacion = 0) AND NEW.puntaje > 0 THEN
        NEW.puntuacion := ROUND((NEW.puntaje / 20.0)::numeric, 2);
    ELSIF (NEW.puntaje IS NULL OR NEW.puntaje = 0) AND NEW.puntuacion > 0 THEN
        NEW.puntaje := ROUND(NEW.puntuacion * 20)::smallint;
    END IF;
    IF NEW.fecha_entrega IS NULL THEN
        NEW.fecha_entrega := COALESCE(NEW.entregado_en, NOW());
    END IF;
    IF NEW.entregado_en IS NULL THEN
        NEW.entregado_en := COALESCE(NEW.fecha_entrega, NOW());
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_sync_entrega_puntuacion
BEFORE INSERT OR UPDATE ON entregas_retos
FOR EACH ROW EXECUTE FUNCTION fn_sync_entrega_puntuacion();

